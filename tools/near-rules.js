// 세도록 맞춥니다(상권업종 소분류가 검색어와 같은 뜻이면 소분류로, 아니면 상호로).
//
// R({...}) 조건 (여러 개면 하나라도 맞으면 됨, 단 big·not은 늘 지켜야 함)
//   name:  상호명에 맞는 정규식
//   small: 소분류명 목록 (이 업종이면 됨)
//   where: 건물명에 맞는 정규식 (영화관·백화점·시장처럼 가게 대신 건물 이름으로 찾는 것)
//   big:   대분류 제한 (예: '음식')
//   only:  소분류가 이 중 하나인 가게만 (상호가 맞아도 업종이 엉뚱하면 뺌. 예: '웨딩갤러리'는 전시가 아님)
//   notBig / notSmall: 이 대분류·소분류는 제외
//   not:   상호명이 이것에 맞으면 제외
//   min:   반경 안에 이만큼 있어야 "있음" (기본 1). 흔한 업종은 2곳 이상으로 잡아, 문 닫은 가게 하나에 속지 않게 합니다.
// 규칙이 없는 카테고리(공원)는 늘 "있음"으로 칩니다.

function R({ name, small, where, big, only, notBig, notSmall, not, min = 1 }) {
  const smalls = small ? new Set(small) : null;
  const onlys = only ? new Set(only) : null;
  const notSmalls = notSmall ? new Set(notSmall) : null;
  const test = s => {
    if (big && s.big !== big) return false;
    if (notBig && s.big === notBig) return false;
    if (onlys && !onlys.has(s.small)) return false;
    if (notSmalls && notSmalls.has(s.small)) return false;
    if (not && not.test(s.name)) return false;
    return !!((name && name.test(s.name)) || (smalls && smalls.has(s.small)) || (where && where.test(s.building)));
  };
  return { test, min };
}
