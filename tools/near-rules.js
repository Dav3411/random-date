// 항목별로 "이 가게면 그 항목을 할 수 있다"고 보는 규칙. tools/build-near.js가 씁니다.
// 가게 한 곳: { name 상호명, branch 지점명, big/mid/small 상권업종 대·중·소분류명, std 표준산업분류명, building 건물명 }
//
// rule({...}) 조건 (여러 개면 하나라도 맞으면 됨, 단 big·not은 늘 지켜야 함)
//   name:  상호명에 맞는 정규식
//   small: 소분류명 목록 (이 업종이면 됨)
//   where: 건물명에 맞는 정규식 (영화관·백화점·시장처럼 가게 대신 건물 이름으로 찾는 것)
//   big:   대분류 제한 (예: '음식')
//   not:   상호명이 이것에 맞으면 제외
// 규칙이 없는 항목(공원 산책처럼 가게가 아닌 것)은 늘 "있음"으로 칩니다.
//
// 확인과 짐작: 상가정보에는 메뉴가 없어서, 어떤 항목은 가게 종류로 짐작할 수밖에 없습니다(빵집이면 휘낭시에도 있겠지).
// 그런 항목은 guess(확인, 짐작, 지도 검색어)로 씁니다.
//   확인: 상호에 그 항목이 드러난 가게. 1곳만 있어도 "있음", 지도는 항목 검색어(마들역 휘낭시에)로 찾습니다.
//   짐작: 그 항목을 팔 만한 종류의 가게. build-near.js의 GUESS_MIN곳 이상일 때만 "있음"으로 치고,
//         지도는 그 가게 종류(마들역 베이커리)로 찾습니다. 네이버는 메뉴·키워드로 찾아서, 짐작한 가게는 항목 이름으로는 안 나올 때가 많습니다.
// guess 없이 함수 하나만 쓴 항목은 모두 확인으로 칩니다.

function rule({ name, small, where, big, not }) {
  const smalls = small ? new Set(small) : null;
  return s => {
    if (big && s.big !== big) return false;
    if (not && not.test(s.name)) return false;
    return !!((name && name.test(s.name)) || (smalls && smalls.has(s.small)) || (where && where.test(s.building)));
  };
}
const F = (name, small, extra) => rule({ big: '음식', name, small, ...extra });
const guess = (sure, maybe, query) => ({ sure, maybe, query });

