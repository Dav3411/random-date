// 한 노선에서 뽑힐 수 있는 모든 경우: 구간(지선 포함) × 세기 시작하는 쪽 × 몇 번째.
// 종점(순환선은 첫 역)을 1번째로 셉니다.
function stationChoices(line) {
  const out = [];
  for (const route of line.routes) {
    const st = route.stations;
    const orders = route.loop
      ? [[st, '내선'], [[st[0], ...st.slice(1).reverse()], '외선']]
      : [[st, null], [[...st].reverse(), null]];
    for (const [order, dir] of orders) {
      const len = order.length;
      const origin = dir
        ? stationLabel(st[0]) + ' 기점 ' + dir + '순환'
        : stationLabel(order[0]) + ' 종점';
      order.forEach((name, i) => out.push({
        line: line.id, name, origin, n: i + 1, len, loop: !!route.loop,
        prev: i > 0 ? order[i - 1] : (route.loop ? order[len - 1] : null),
        next: i < len - 1 ? order[i + 1] : (route.loop ? order[0] : null),
        first: st[0], last: st[len - 1],
      }));
    }
  }
  return out;
}

// skip에 든 역 이름은 빼고 하나를 뽑습니다. 남은 역이 없으면 null.
function drawStation(line, skip) {
  const pool = stationChoices(line).filter(c => !skip || !skip.has(c.name));
  return pool.length ? pickOne(pool) : null;
}
